pub const TOKSI_OWNED_MARKER: &str = super::TOKSI_OWNED_MARKER;
pub const TOKSI_OWNED_KEYS: &str = super::TOKSI_OWNED_KEYS;
pub const TOKLESS_OWNED_MARKER: &str = super::TOKLESS_OWNED_MARKER;
pub const TOKLESS_OWNED_KEYS: &str = super::TOKLESS_OWNED_KEYS;
pub const MANAGED_PROXY_KEYS: &[&str] = super::MANAGED_PROXY_KEYS;

const ENVIRONMENT_D_HEADER: &str = "# Auto-generated by toksi daemon (managed environment)";

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct UnixEnvSnapshot {
    pub env_d_original: Option<String>,
    pub systemd_originals: Vec<(String, Option<String>)>,
    pub launchctl_originals: Vec<(String, Option<String>)>,
    pub keys: Vec<String>,
}

pub fn get_environment_d_conf_path() -> Option<PathBuf> {
    dirs::config_dir().map(|c| {
        let p = c.join("environment.d").join("99-toksi.conf");
        PathBuf::from(normalize_path(&p.to_string_lossy()))
    })
}

pub fn get_legacy_environment_d_conf_path() -> Option<PathBuf> {
    dirs::config_dir().map(|c| {
        let p = c.join("environment.d").join("99-tokless.conf");
        PathBuf::from(normalize_path(&p.to_string_lossy()))
    })
}

/// Formats `~/.config/environment.d/99-toksi.conf` content cleanly using forward-slash paths.
pub fn format_environment_d_content(vars: &[(&str, &str)], keys_csv: &str) -> String {
    let mut content = String::from(ENVIRONMENT_D_HEADER);
    content.push('\n');
    for &(key, val) in vars {
        if is_forbidden_auth_bypass_key(key) {
            continue;
        }
        let clean_val = sanitize_env_value(key, val);
        content.push_str(&format!("{}=\"{}\"\n", key, clean_val));
    }
    content.push_str(&format!("{}=\"1\"\n", TOKSI_OWNED_MARKER));
    content.push_str(&format!("{}=\"{}\"\n", TOKSI_OWNED_KEYS, keys_csv));
    content
}

/// Formats POSIX shell session exports (for interactive shell eval / user session hooks).
pub fn format_posix_session_exports(vars: &[(&str, &str)]) -> String {
    let mut out = String::new();
    for &(key, val) in vars {
        if is_forbidden_auth_bypass_key(key) {
            continue;
        }
        let clean_val = sanitize_env_value(key, val).replace('"', "\\\"");
        out.push_str(&format!("export {}=\"{}\"\n", key, clean_val));
    }
    out.push_str(&format!("unset {}\n", CLOUD_CODE_URL_KEY));
    out
}

/// Parses `KEY="VAL"` / `KEY=VAL` entries from an `environment.d` `.conf` file.
pub fn read_environment_d_entries(path: &Path) -> BTreeMap<String, String> {
    let Ok(raw) = fs::read_to_string(path) else {
        return BTreeMap::new();
    };
    let mut out = BTreeMap::new();
    for line in raw.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        if let Some((k, v)) = trimmed.split_once('=') {
            let key = k.trim();
            let val = v.trim().trim_matches('"').trim_matches('\'');
            if !key.is_empty() {
                out.insert(key.to_string(), val.to_string());
            }
        }
    }
    out
}

fn check_unix_service_tool(tool: &str) -> bool {
    match check_executable_in_path(tool) {
        Ok(()) => true,
        Err(msg) => {
            L.debug(&format!("Unix environment manager tool '{}' unavailable: {}", tool, msg));
            false
        }
    }
}

fn query_systemd_user_env() -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    if !cfg!(target_os = "linux") || !check_unix_service_tool("systemctl") {
        return out;
    }
    let Ok(output) = Command::new("systemctl")
        .args(["--user", "show-environment"])
        .output()
    else {
        return out;
    };
    if !output.status.success() {
        return out;
    }
    let stdout = String::from_utf8_lossy(&output.stdout);
    for line in stdout.lines() {
        if let Some((k, v)) = line.split_once('=') {
            out.insert(k.trim().to_string(), v.to_string());
        }
    }
    out
}

fn query_launchctl_env(key: &str) -> Option<String> {
    if !cfg!(target_os = "macos") || !check_unix_service_tool("launchctl") {
        return None;
    }
    let Ok(output) = Command::new("launchctl").args(["getenv", key]).output() else {
        return None;
    };
    if !output.status.success() {
        return None;
    }
    let val = String::from_utf8_lossy(&output.stdout).trim().to_string();
    if val.is_empty() {
        None
    } else {
        Some(val)
    }
}

/// Captures original Unix environment state (`environment.d`, `systemd --user`, `launchctl`).
pub fn capture_unix_env_snapshot(
    keys: &[&str],
    conf_path: Option<&Path>,
    query_service_managers: bool,
) -> UnixEnvSnapshot {
    let clean_keys: Vec<String> = keys
        .iter()
        .filter(|&&k| !is_forbidden_auth_bypass_key(k))
        .map(|&k| k.to_string())
        .collect();

    let env_d_original = conf_path.and_then(|p| {
        if !p.is_file() {
            return None;
        }
        let raw = fs::read_to_string(p).ok()?;
        if raw.contains(ENVIRONMENT_D_HEADER) {
            None
        } else {
            Some(raw)
        }
    });

    let mut systemd_originals = Vec::new();
    let mut launchctl_originals = Vec::new();

    if query_service_managers {
        if cfg!(target_os = "linux") {
            let current = query_systemd_user_env();
            for k in &clean_keys {
                systemd_originals.push((k.clone(), current.get(k).cloned()));
            }
        }
        if cfg!(target_os = "macos") {
            for k in &clean_keys {
                launchctl_originals.push((k.clone(), query_launchctl_env(k)));
            }
        }
    }

    UnixEnvSnapshot {
        env_d_original,
        systemd_originals,
        launchctl_originals,
        keys: clean_keys,
    }
}

pub fn inject_unix_env_vars_in(
    vars: &[(&str, &str)],
    conf_path: Option<&Path>,
    run_service_cmds: bool,
) -> Result<Vec<String>, EnvInjectorError> {
    let filtered: Vec<(&str, String)> = vars
        .iter()
        .filter(|(k, _)| !is_forbidden_auth_bypass_key(k))
        .map(|&(k, v)| (k, sanitize_env_value(k, v)))
        .collect();

    let mut injected = Vec::with_capacity(filtered.len() + 2);
    let keys: Vec<&str> = filtered.iter().map(|(k, _)| *k).collect();
    let keys_csv = keys.join(",");

    let overlay_pairs: Vec<(&str, &str)> = filtered.iter().map(|(k, v)| (*k, v.as_str())).collect();
    overlay_apply_vars(&overlay_pairs, TOKSI_OWNED_MARKER, &keys_csv);
    for (k, _) in &filtered {
        injected.push((*k).to_string());
    }
    injected.push(TOKSI_OWNED_MARKER.to_string());
    injected.push(TOKSI_OWNED_KEYS.to_string());

    if run_service_cmds {
        // Linux: systemd --user set-environment
        if cfg!(target_os = "linux") && check_unix_service_tool("systemctl") {
            let mut cmd = Command::new("systemctl");
            cmd.args(["--user", "set-environment"]);
            for (key, val) in &filtered {
                cmd.arg(format!("{}={}", key, val));
            }
            cmd.arg(format!("{}=1", TOKSI_OWNED_MARKER));
            cmd.arg(format!("{}={}", TOKSI_OWNED_KEYS, keys_csv));
            let _ = cmd.output();

            let _ = Command::new("systemctl")
                .args(["--user", "unset-environment", CLOUD_CODE_URL_KEY])
                .output();
        }

        // macOS: launchctl setenv
        if cfg!(target_os = "macos") && check_unix_service_tool("launchctl") {
            for (key, val) in &filtered {
                let _ = Command::new("launchctl")
                    .args(["setenv", key, val])
                    .output();
            }
            let _ = Command::new("launchctl")
                .args(["unsetenv", CLOUD_CODE_URL_KEY])
                .output();
            let _ = Command::new("launchctl")
                .args(["setenv", TOKSI_OWNED_MARKER, "1"])
                .output();
            let _ = Command::new("launchctl")
                .args(["setenv", TOKSI_OWNED_KEYS, &keys_csv])
                .output();
        }
    }

    // environment.d drop-in configuration file (Linux & XDG-compliant user sessions)
    if let Some(path) = conf_path {
        let norm_path = PathBuf::from(normalize_path(&path.to_string_lossy()));
        let content = format_environment_d_content(&overlay_pairs, &keys_csv);
        write_file_atomic(&norm_path, &content).map_err(|source| EnvInjectorError::Io {
            path: normalize_path(&norm_path.to_string_lossy()),
            source,
        })?;
    }

    Ok(injected)
}

pub fn inject_unix_env_vars(vars: &[(&str, &str)]) -> Result<Vec<String>, EnvInjectorError> {
    let conf_path = get_environment_d_conf_path();
    inject_unix_env_vars_in(vars, conf_path.as_deref(), cfg!(unix))
}

pub fn inject_unix_env(proxy_url: &str) -> Result<Vec<String>, EnvInjectorError> {
    let vars: Vec<(&str, &str)> = MANAGED_PROXY_KEYS.iter().map(|&k| (k, proxy_url)).collect();
    inject_unix_env_vars(&vars)
}

pub fn restore_unix_env_snapshot(
    snapshot: &UnixEnvSnapshot,
    conf_path: Option<&Path>,
    legacy_conf_path: Option<&Path>,
    run_service_cmds: bool,
) -> Result<Vec<String>, EnvInjectorError> {
    let mut purged = Vec::new();

    // 1. Restore or remove environment.d drop-in
    if let Some(path) = conf_path {
        let norm_path = PathBuf::from(normalize_path(&path.to_string_lossy()));
        if let Some(ref orig_content) = snapshot.env_d_original {
            write_file_atomic(&norm_path, orig_content).map_err(|source| EnvInjectorError::Io {
                path: normalize_path(&norm_path.to_string_lossy()),
                source,
            })?;
        } else if norm_path.exists() {
            fs::remove_file(&norm_path).map_err(|source| EnvInjectorError::Io {
                path: normalize_path(&norm_path.to_string_lossy()),
                source,
            })?;
        }
    }
    if let Some(legacy_path) = legacy_conf_path
        && legacy_path.exists()
    {
        let _ = fs::remove_file(legacy_path);
    }

    let mut all_keys = snapshot.keys.clone();
    for &k in MANAGED_PROXY_KEYS {
        if !all_keys.iter().any(|existing| existing == k) {
            all_keys.push(k.to_string());
        }
    }

    if run_service_cmds {
        // 2. systemd user environment (Linux)
        if cfg!(target_os = "linux") && check_unix_service_tool("systemctl") {
            let mut set_pairs = Vec::new();
            let mut unset_keys = Vec::new();

            for (k, orig) in &snapshot.systemd_originals {
                match orig {
                    Some(val) => set_pairs.push(format!("{}={}", k, val)),
                    None => unset_keys.push(k.clone()),
                }
            }
            for k in &all_keys {
                if !snapshot.systemd_originals.iter().any(|(sk, _)| sk == k)
                    && !unset_keys.contains(k)
                {
                    unset_keys.push(k.clone());
                }
            }
            for marker in [
                CLOUD_CODE_URL_KEY,
                TOKSI_OWNED_MARKER,
                TOKSI_OWNED_KEYS,
                TOKLESS_OWNED_MARKER,
                TOKLESS_OWNED_KEYS,
            ] {
                unset_keys.push(marker.to_string());
            }

            if !set_pairs.is_empty() {
                let mut cmd = Command::new("systemctl");
                cmd.args(["--user", "set-environment"]);
                for pair in &set_pairs {
                    cmd.arg(pair);
                }
                let _ = cmd.output();
            }
            if !unset_keys.is_empty() {
                let mut cmd = Command::new("systemctl");
                cmd.args(["--user", "unset-environment"]);
                for k in &unset_keys {
                    cmd.arg(k);
                }
                let _ = cmd.output();
            }
        }

        // 3. launchctl user session environment (macOS)
        if cfg!(target_os = "macos") && check_unix_service_tool("launchctl") {
            for (k, orig) in &snapshot.launchctl_originals {
                match orig {
                    Some(val) => {
                        let _ = Command::new("launchctl")
                            .args(["setenv", k, val])
                            .output();
                    }
                    None => {
                        let _ = Command::new("launchctl").args(["unsetenv", k]).output();
                    }
                }
            }
            for k in &all_keys {
                if !snapshot.launchctl_originals.iter().any(|(lk, _)| lk == k) {
                    let _ = Command::new("launchctl").args(["unsetenv", k]).output();
                }
            }
            for marker in [
                CLOUD_CODE_URL_KEY,
                TOKSI_OWNED_MARKER,
                TOKSI_OWNED_KEYS,
                TOKLESS_OWNED_MARKER,
                TOKLESS_OWNED_KEYS,
            ] {
                let _ = Command::new("launchctl")
                    .args(["unsetenv", marker])
                    .output();
            }
        }
    }

    // 4. Clear safe in-memory overlay
    let key_refs: Vec<&str> = all_keys.iter().map(String::as_str).collect();
    overlay_restore_or_clear(&[], &key_refs);

    purged.extend(all_keys);
    purged.push(TOKSI_OWNED_MARKER.to_string());
    purged.push(TOKSI_OWNED_KEYS.to_string());
    purged.push(TOKLESS_OWNED_MARKER.to_string());
    purged.push(TOKLESS_OWNED_KEYS.to_string());

    Ok(purged)
}

pub fn teardown_unix_env_in(
    conf_path: Option<&Path>,
    legacy_conf_path: Option<&Path>,
    run_service_cmds: bool,
) -> Result<Vec<String>, EnvInjectorError> {
    let empty_snapshot = UnixEnvSnapshot {
        env_d_original: None,
        systemd_originals: Vec::new(),
        launchctl_originals: Vec::new(),
        keys: MANAGED_PROXY_KEYS.iter().map(|&k| k.to_string()).collect(),
    };
    restore_unix_env_snapshot(&empty_snapshot, conf_path, legacy_conf_path, run_service_cmds)
}

pub fn teardown_unix_env() -> Result<Vec<String>, EnvInjectorError> {
    let conf_path = get_environment_d_conf_path();
    let legacy_path = get_legacy_environment_d_conf_path();
    teardown_unix_env_in(conf_path.as_deref(), legacy_path.as_deref(), cfg!(unix))
}

#[cfg(test)]
mod tests {
    use super::*;

    type TestResult = Result<(), Box<dyn std::error::Error>>;

    #[test]
    fn test_unix_env_inject_and_teardown() -> TestResult {
        let Ok(_lock) = crate::env_injector::TEST_ENV_LOCK.lock() else {
            return Ok(());
        };
        let dir = tempfile::tempdir()?;
        let conf_path = PathBuf::from(normalize_path(
            &dir.path().join("99-toksi.conf").to_string_lossy(),
        ));
        let legacy_path = PathBuf::from(normalize_path(
            &dir.path().join("99-tokless.conf").to_string_lossy(),
        ));

        let res = inject_unix_env_vars_in(
            &[
                ("GOOGLE_GEMINI_BASE_URL", "http://127.0.0.1:8787"),
                ("ANTHROPIC_BASE_URL", "http://127.0.0.1:8787"),
                ("CLOUD_CODE_URL", "http://should-never-be-injected"),
            ],
            Some(&conf_path),
            false,
        )?;
        assert!(res.contains(&"GOOGLE_GEMINI_BASE_URL".to_string()));
        assert!(!res.contains(&CLOUD_CODE_URL_KEY.to_string()));
        assert!(conf_path.is_file());

        let parsed = read_environment_d_entries(&conf_path);
        assert_eq!(
            parsed.get("GOOGLE_GEMINI_BASE_URL").map(String::as_str),
            Some("http://127.0.0.1:8787")
        );
        assert_eq!(
            parsed.get("ANTHROPIC_BASE_URL").map(String::as_str),
            Some("http://127.0.0.1:8787")
        );
        assert_eq!(parsed.get(TOKSI_OWNED_MARKER).map(String::as_str), Some("1"));
        assert!(!parsed.contains_key(CLOUD_CODE_URL_KEY));

        assert_eq!(
            crate::env_injector::effective_env_var("GOOGLE_GEMINI_BASE_URL").as_deref(),
            Some("http://127.0.0.1:8787")
        );
        assert_eq!(
            crate::env_injector::effective_env_var(CLOUD_CODE_URL_KEY),
            None
        );

        let purged = teardown_unix_env_in(Some(&conf_path), Some(&legacy_path), false)?;
        assert!(purged.contains(&"GOOGLE_GEMINI_BASE_URL".to_string()));
        assert!(!conf_path.exists());
        assert_eq!(
            crate::env_injector::effective_env_var("GOOGLE_GEMINI_BASE_URL"),
            None
        );
        Ok(())
    }

    #[test]
    fn test_unix_snapshot_restores_custom_environment_d() -> TestResult {
        let Ok(_lock) = crate::env_injector::TEST_ENV_LOCK.lock() else {
            return Ok(());
        };
        let dir = tempfile::tempdir()?;
        let conf_path = dir.path().join("99-toksi.conf");
        let original = "CUSTOM_USER_VAR=\"keep-me\"\n";
        fs::write(&conf_path, original)?;

        let snapshot = capture_unix_env_snapshot(MANAGED_PROXY_KEYS, Some(&conf_path), false);
        assert_eq!(snapshot.env_d_original.as_deref(), Some(original));

        inject_unix_env_vars_in(
            &[("GOOGLE_GEMINI_BASE_URL", "http://127.0.0.1:8787")],
            Some(&conf_path),
            false,
        )?;
        let during = fs::read_to_string(&conf_path)?;
        assert!(during.contains("GOOGLE_GEMINI_BASE_URL"));

        restore_unix_env_snapshot(&snapshot, Some(&conf_path), None, false)?;
        let after = fs::read_to_string(&conf_path)?;
        assert_eq!(after, original);
        Ok(())
    }

    #[test]
    fn test_format_posix_session_exports_excludes_cloud_code_url() {
        let script = format_posix_session_exports(&[
            ("GOOGLE_GEMINI_BASE_URL", "http://127.0.0.1:8787"),
            ("CLOUD_CODE_URL", "http://bad"),
            ("TOKSI_ROOT_DIR", r"C:\Users\dev\.toksi"),
        ]);
        assert!(script.contains("export GOOGLE_GEMINI_BASE_URL=\"http://127.0.0.1:8787\""));
        assert!(script.contains("export TOKSI_ROOT_DIR=\"C:/Users/dev/.toksi\""));
        assert!(!script.contains("export CLOUD_CODE_URL"));
        assert!(script.contains("unset CLOUD_CODE_URL"));
    }

    #[test]
    fn test_environment_d_paths_use_forward_slashes() {
        if let Some(p) = get_environment_d_conf_path() {
            assert!(!p.to_string_lossy().contains('\\'));
        }
        if let Some(p) = get_legacy_environment_d_conf_path() {
            assert!(!p.to_string_lossy().contains('\\'));
        }
    }
}
