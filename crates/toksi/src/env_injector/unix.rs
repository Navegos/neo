use std::fs;
use std::path::PathBuf;
use std::process::Command;

pub const TOKSI_OWNED_MARKER: &str = "TOKSI_OWNED";
pub const TOKSI_OWNED_KEYS: &str = "TOKSI_OWNED_KEYS";
pub const TOKLESS_OWNED_MARKER: &str = "TOKLESS_OWNED";
pub const TOKLESS_OWNED_KEYS: &str = "TOKLESS_OWNED_KEYS";

pub const MANAGED_PROXY_KEYS: &[&str] = &[
    "GOOGLE_GEMINI_BASE_URL",
    "ANTHROPIC_BASE_URL",
];

pub fn get_environment_d_conf_path() -> Option<PathBuf> {
    dirs::config_dir().map(|c| c.join("environment.d").join("99-toksi.conf"))
}

pub fn get_legacy_environment_d_conf_path() -> Option<PathBuf> {
    dirs::config_dir().map(|c| c.join("environment.d").join("99-tokless.conf"))
}

pub fn inject_unix_env(proxy_url: &str) -> Result<Vec<String>, String> {
    let mut injected = Vec::new();
    let keys_csv = MANAGED_PROXY_KEYS.join(",");

    // 1. Process environment
    unsafe {
        for &key in MANAGED_PROXY_KEYS {
            std::env::set_var(key, proxy_url);
            injected.push(key.to_string());
        }
        std::env::set_var(TOKSI_OWNED_MARKER, "1");
        std::env::set_var(TOKSI_OWNED_KEYS, &keys_csv);
    }
    injected.push(TOKSI_OWNED_MARKER.to_string());
    injected.push(TOKSI_OWNED_KEYS.to_string());

    // 2. systemd user environment (if available)
    if which::which("systemctl").is_ok() {
        let mut cmd = Command::new("systemctl");
        cmd.args(["--user", "set-environment"]);
        for &key in MANAGED_PROXY_KEYS {
            cmd.arg(format!("{}={}", key, proxy_url));
        }
        cmd.arg(format!("{}=1", TOKSI_OWNED_MARKER));
        cmd.arg(format!("{}={}", TOKSI_OWNED_KEYS, keys_csv));
        let _ = cmd.output();
    }

    // 3. environment.d drop-in configuration file
    if let Some(conf_path) = get_environment_d_conf_path() {
        if let Some(parent) = conf_path.parent() {
            let _ = fs::create_dir_all(parent);
        }
        let mut content = String::from("# Auto-generated by toksi daemon (managed environment)\n");
        for &key in MANAGED_PROXY_KEYS {
            content.push_str(&format!("{}=\"{}\"\n", key, proxy_url));
        }
        content.push_str(&format!("{}=\"1\"\n", TOKSI_OWNED_MARKER));
        content.push_str(&format!("{}=\"{}\"\n", TOKSI_OWNED_KEYS, keys_csv));
        let _ = fs::write(conf_path, content);
    }

    Ok(injected)
}

pub fn teardown_unix_env() -> Result<Vec<String>, String> {
    let mut purged = Vec::new();

    // 1. Remove environment.d drop-in
    if let Some(conf_path) = get_environment_d_conf_path() {
        if conf_path.exists() {
            let _ = fs::remove_file(conf_path);
        }
    }
    if let Some(legacy_conf) = get_legacy_environment_d_conf_path() {
        if legacy_conf.exists() {
            let _ = fs::remove_file(legacy_conf);
        }
    }

    // 2. systemd user environment
    if which::which("systemctl").is_ok() {
        let mut cmd = Command::new("systemctl");
        cmd.args(["--user", "unset-environment"]);
        for &key in MANAGED_PROXY_KEYS {
            cmd.arg(key);
        }
        cmd.arg(TOKSI_OWNED_MARKER);
        cmd.arg(TOKSI_OWNED_KEYS);
        cmd.arg(TOKLESS_OWNED_MARKER);
        cmd.arg(TOKLESS_OWNED_KEYS);
        let _ = cmd.output();
    }

    // 3. Process environment
    unsafe {
        for &key in MANAGED_PROXY_KEYS {
            std::env::remove_var(key);
            purged.push(key.to_string());
        }
        std::env::remove_var(TOKSI_OWNED_MARKER);
        std::env::remove_var(TOKSI_OWNED_KEYS);
        std::env::remove_var(TOKLESS_OWNED_MARKER);
        std::env::remove_var(TOKLESS_OWNED_KEYS);
    }
    purged.push(TOKSI_OWNED_MARKER.to_string());
    purged.push(TOKSI_OWNED_KEYS.to_string());
    purged.push(TOKLESS_OWNED_MARKER.to_string());
    purged.push(TOKLESS_OWNED_KEYS.to_string());

    Ok(purged)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_unix_env_inject_and_teardown() {
        let res = inject_unix_env("http://127.0.0.1:8787");
        assert!(res.is_ok());
        assert_eq!(std::env::var("GOOGLE_GEMINI_BASE_URL").unwrap(), "http://127.0.0.1:8787");

        let purged = teardown_unix_env();
        assert!(purged.is_ok());
        assert!(std::env::var("GOOGLE_GEMINI_BASE_URL").is_err());
    }
}
